import { chromium } from '@playwright/test';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const output=process.argv[2]??'work/multi-product-0.2.1';fs.mkdirSync(output,{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,args:['--force_high_performance_gpu']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const report={errors};
try {
  await page.goto('http://127.0.0.1:1420/');
  await page.waitForFunction(()=>document.querySelector('[data-testid="viewport"]')?.dataset.rendererState==='ready');
  await page.getByRole('button',{name:'Футболка',exact:true}).click();
  await page.getByLabel('Продукт',{exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Продукт"]').value==='tshirt-gildan-5000'&&!document.querySelector('[aria-label="Продукт"]').disabled);
  await page.getByTestId('image-input').setInputFiles('tests/fixtures/color-patches.png');
  await page.waitForFunction(()=>!document.querySelector('[aria-label="Продукт"]').disabled);
  await page.screenshot({path:`${output}/shirt-front-ui.png`});
  await page.getByRole('button',{name:'Сзади',exact:true}).first().click();
  await page.waitForFunction(()=>!document.querySelector('[aria-label="Продукт"]').disabled);
  await page.getByTestId('image-input').setInputFiles('tests/fixtures/landscape-grid.png');
  await page.waitForFunction(()=>!document.querySelector('[aria-label="Продукт"]').disabled);
  await page.screenshot({path:`${output}/shirt-back-ui.png`});
  await page.getByRole('button',{name:'Спереди',exact:true}).first().click();
  await page.waitForFunction(()=>!document.querySelector('[aria-label="Продукт"]').disabled);
  report.frontRestored=await page.getByText('color-patches.png',{exact:true}).count()>0;
  assert.ok(report.frontRestored,'Front artwork must survive editing the back');
  await page.getByRole('button',{name:'Кружка',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Продукт"]').value==='mug-11oz'&&!document.querySelector('[aria-label="Продукт"]').disabled);
  await page.getByTestId('image-input').setInputFiles('tests/fixtures/panorama-grid.png');
  await page.waitForFunction(()=>!document.querySelector('[aria-label="Продукт"]').disabled);
  await page.screenshot({path:`${output}/mug-ui.png`});
  await page.getByRole('button',{name:'Коврик',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Продукт"]').value==='deskmat-900x400'&&!document.querySelector('[aria-label="Продукт"]').disabled);
  await page.screenshot({path:`${output}/mat-ui.png`});
  await page.goto('http://127.0.0.1:1420/tests/realism-probe.html');
  report.model=await page.evaluate(async()=>{
    const {StudioScene}=await import('/src/scene/StudioScene.ts');
    const api=await import('/src/project/index.ts');
    const {getProduct}=await import('/src/products/index.ts');
    const state=api.createDefaultProject('tshirt-gildan-5000');state.realism.mode='fast';
    const canvas=document.createElement('canvas');canvas.width=canvas.height=256;const ctx=canvas.getContext('2d');ctx.fillStyle='#ff0000';ctx.fillRect(0,0,256,256);
    state.source={name:'front-red.png',mimeType:'image/png',widthPx:256,heightPx:256,dataUrl:canvas.toDataURL()};
    ctx.fillStyle='#0000ff';ctx.fillRect(0,0,256,256);
    state.sidePrints.back={source:{...state.source,name:'back-blue.png',dataUrl:canvas.toDataURL()},layout:{...state.layout}};
    const live=new StudioScene(document.querySelector('#host'),state,e=>{if(e)console.error(e);});
    await live.loadProject(state);
    const pixel=(side,x,y)=>Array.from(live.merch.canvases[side].getContext('2d').getImageData(x,y,1,1).data);
    const front=pixel('front',1024,1024),back=pixel('back',1024,1024),neck=pixel('front',1024,150);
    const restored=api.parseProject(api.serializeProject(state));
    const photo=await live.preparePhoto(512,new AbortController().signal,'studio');const photoMeshes=photo.scene.children.length;photo.dispose();
    const mug=api.createDefaultProject('mug-11oz');mug.realism.mode='fast';mug.source=state.source;await live.loadProject(mug);
    const mugCanvas=live.merch.canvases.front,mc=mugCanvas.getContext('2d');
    const handleGap=Array.from(mc.getImageData(0,750,1,1).data),rim=Array.from(mc.getImageData(2048,0,1,1).data);
    const p=getProduct(mug.productId);const gap=p.widthMm-p.printableArea.widthMm;
    const blob=await live.exportPng({widthPx:960,heightPx:600});
    const bytes=Array.from(new Uint8Array(await blob.arrayBuffer()));
    live.dispose();
    return {front,back,neck,backSaved:restored.sidePrints.back.source.name,photoMeshes,handleGap,rim,gap,bytes};
  });
  fs.writeFileSync(`${output}/mug-export.png`,Buffer.from(report.model.bytes));delete report.model.bytes;
  assert.ok(report.model.front[0]>240&&report.model.front[2]<10);
  assert.ok(report.model.back[2]>240&&report.model.back[0]<10);
  assert.equal(report.model.backSaved,'back-blue.png');
  assert.ok(report.model.neck[0]>200&&report.model.neck[2]>200,'Collar must remain unprinted');
  assert.deepEqual(report.model.handleGap,[255,255,255,255]);assert.deepEqual(report.model.rim,[255,255,255,255]);
  assert.ok(report.model.gap>40);assert.equal(errors.length,0,errors.join('\n'));
  fs.writeFileSync(`${output}/report.json`,JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally {await browser.close();}
